// Generates the tray icons from the SVG below (the FrameCapt mark: a rounded frame with capture
// corner brackets; the recording variant adds a red dot). Run: node scripts/generate-tray-icons.mjs
//
// Output (committed): assets/tray/tray-{16,24,32}.png, tray-recording-{16,24,32}.png (100%, 150% and
// 200% display scaling), assets/tray/framecapt.ico (PNG-compressed 16/24/32/48/64) and
// src/main/tray-icons.generated.ts (the same PNGs as base64, so the app needs no extra files at runtime),
// and the application/installer icon assets/app/framecapt.ico (PNG-compressed 16/24/32/48/64/128/256).
//
// Tooling licenses: @napi-rs/canvas (MIT) renders the SVG; it is a devDependency and is not shipped.
// The artwork is original to this project (GPL-3.0-only, like the rest of the repository).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createCanvas, loadImage } from '@napi-rs/canvas';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetsDir = path.join(root, 'assets', 'tray');
const SIZES = [16, 24, 32];
const ICO_SIZES = [16, 24, 32, 48, 64];
const APP_ICO_SIZES = [16, 24, 32, 48, 64, 128, 256];
const appDir = path.join(root, 'assets', 'app');

function svg(size, recording) {
  const dot = recording
    ? `<circle cx="24" cy="24" r="7.5" fill="#ef4444" stroke="#ffffff" stroke-width="2.2"/>`
    : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 32 32">
  <defs>
    <linearGradient id="g" x1="4" y1="2" x2="28" y2="30" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#6366f1"/>
      <stop offset="1" stop-color="#8b5cf6"/>
    </linearGradient>
  </defs>
  <rect x="1" y="1" width="30" height="30" rx="9" fill="url(#g)"/>
  <path d="M10 15.5V13a3 3 0 0 1 3-3h2.5" fill="none" stroke="#fff" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/>
  <path d="M22 16.5V19a3 3 0 0 1-3 3h-2.5" fill="none" stroke="#fff" stroke-opacity="0.8" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/>
  ${dot}
</svg>`;
}

async function render(size, recording) {
  const image = await loadImage(Buffer.from(svg(size, recording)));
  const canvas = createCanvas(size, size);
  canvas.getContext('2d').drawImage(image, 0, 0, size, size);
  return canvas.toBuffer('image/png');
}

/** An ICO file whose images are PNGs (supported since Windows Vista). */
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  const entries = Buffer.alloc(16 * images.length);
  let offset = header.length + entries.length;
  images.forEach(({ size, png }, index) => {
    const at = index * 16;
    entries[at] = size >= 256 ? 0 : size;
    entries[at + 1] = size >= 256 ? 0 : size;
    entries.writeUInt16LE(1, at + 4); // planes
    entries.writeUInt16LE(32, at + 6); // bits per pixel
    entries.writeUInt32LE(png.length, at + 8);
    entries.writeUInt32LE(offset, at + 12);
    offset += png.length;
  });
  return Buffer.concat([header, entries, ...images.map((image) => image.png)]);
}

fs.mkdirSync(assetsDir, { recursive: true });
const generated = { normal: {}, recording: {} };
for (const size of SIZES) {
  const normal = await render(size, false);
  const recording = await render(size, true);
  fs.writeFileSync(path.join(assetsDir, `tray-${size}.png`), normal);
  fs.writeFileSync(path.join(assetsDir, `tray-recording-${size}.png`), recording);
  generated.normal[size] = normal.toString('base64');
  generated.recording[size] = recording.toString('base64');
}
const icoImages = [];
for (const size of ICO_SIZES) icoImages.push({ size, png: await render(size, false) });
fs.writeFileSync(path.join(assetsDir, 'framecapt.ico'), ico(icoImages));

// The application icon (exe, Setup.exe, Update.exe, shortcuts): same mark, including 128 and 256 px.
fs.mkdirSync(appDir, { recursive: true });
const appImages = [];
for (const size of APP_ICO_SIZES) appImages.push({ size, png: await render(size, false) });
fs.writeFileSync(path.join(appDir, 'framecapt.ico'), ico(appImages));

const source = `// Generated by scripts/generate-tray-icons.mjs. Do not edit.
/** Tray icon PNGs (base64) by size: 16, 24 and 32 px for 100%, 150% and 200% display scaling. */
export const TRAY_ICONS = ${JSON.stringify(generated, null, 2)} as const;
`;
fs.writeFileSync(path.join(root, 'src', 'main', 'tray-icons.generated.ts'), source);
console.log('Icons written to assets/tray, assets/app and src/main/tray-icons.generated.ts');
